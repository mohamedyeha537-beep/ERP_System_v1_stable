def get_guest_id_types(db: Session) -> list[str]:
    raw = (get_setting(db, SETTING_ID_TYPES, "") or "").strip()
    if raw:
        try:
            data = json.loads(raw)
            if isinstance(data, list):
                out = [str(x).strip() for x in data if str(x).strip()]
                if out:
                    return out
        except json.JSONDecodeError:
            pass
    return list(DEFAULT_ID_TYPES)


def save_guest_id_types(db: Session, lines: str) -> list[str]:
    types = [ln.strip() for ln in (lines or "").splitlines() if ln.strip()]
    if not types:
        types = list(DEFAULT_ID_TYPES)
    set_setting(db, SETTING_ID_TYPES, json.dumps(types, ensure_ascii=False))
    return types


def guest_form_context(db: Session) -> dict:
    return {
        "guest_id_types": get_guest_id_types(db),
        "nationalities": list(NATIONALITIES_AR),
        "default_nationality": DEFAULT_NATIONALITY,
    }
